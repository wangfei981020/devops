/**
 * 集群名的**唯一**展示口径。
 *
 * # 为什么必须收口到一处
 *
 * 只有部分集群配了中文别名。写成 `displayName || name` 时，配了别名的那个
 * 显示「开发环境集群」，另外三个显示原名 —— 四个选项混着两套命名，
 * 用户无从判断「开发环境集群」是哪一个、和另外三个是不是同一套体系
 * （OPSCMDB-031 NEW-3/5，生产上先后在 4 个页面被撞见）。
 *
 * 🔴 而且这类问题**按页面修是修不完的**：每加一个显示集群名的地方，
 * 就多一处可能写错的实现。已经修过资源使用率页一处，随后又在
 * `/platform/pipelines`、`/k8s/disruption` 上冒出来 —— 那不是"又漏了两处"，
 * 是这件事本来就该只有一处实现。
 *
 * ⚠️ 原名必须**始终可见**：它是接口、MCP 工具、PromQL 标签里用的标识。
 * 别名只是给人看的加注，不能替代它。
 */
export function clusterLabel(displayName?: string | null, name?: string | null): string {
  const n = (name ?? '').trim()
  const d = (displayName ?? '').trim()
  // 没有别名、或别名与原名相同 → 只显示原名（不要拼成「x（x）」）
  if (d === '' || d === n) return n
  // ⚠️ 没有原名时只能显示别名。这种情况本身是数据问题，
  //	但显示成「（）」或空白更糟 —— 那看起来像渲染坏了
  if (n === '') return d
  return `${d}（${n}）`
}
