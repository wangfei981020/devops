-- summary 放宽到 TEXT。
--
-- 原来是 VARCHAR(255)，配 truncate(summary, 250) 刚好够装「危险 1 项、偏高 3 项」这种纯计数摘要。
-- 现在摘要要带上具体对象（不然看不出该处置什么），长度立刻涨上去——
-- 实测 3 个集群 4 个超标项就已经 222 字符，再多两个集群必被截断，
-- 而被截掉的恰恰是排在最后的「N 个集群未接入监控未检查」这段，
-- 又变回"看起来全查过了"的假象。
--
-- 列表页对长摘要做省略显示，完整内容在详情抽屉里看。
ALTER TABLE task_run_logs MODIFY COLUMN summary TEXT NULL COMMENT '结果摘要（含具体对象，长度不设紧上限）';
