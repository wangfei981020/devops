-- MCP 令牌加可选有效期。
--
-- # 为什么
--
-- 这是一个**能只读访问全库 87 个工具**的凭据（资产、成本、IAM、暴露面、日志），
-- 而它**永不失效** —— 接口里没有任何 expires_at/ttl 字段，
-- 界面上也看不出它什么时候会失效，因为它不会（OPSCMDB-031 P1-70）。
--
-- 现实里这类令牌会被贴进某个人的配置文件、某台机器的环境变量，
-- 然后那个人换岗、那台机器被回收，而令牌一直活着。
-- 「谁在用」这个问题只有 last_used_at 能部分回答，
-- 而"没人用了"和"被别人捡去用了"看起来一模一样。
--
-- # ⚠️ 为什么允许为空（永久）
--
-- 强制有效期会逼所有人定期换令牌，而换令牌这件事一旦漏做，
-- 表现是 AI 突然全线 401 —— 在没有到期提醒的产品里这是净损失。
-- 所以：默认永久（NULL），**但界面必须把"永久"明说出来**，
-- 让它是一个看得见的决定而不是一个看不见的默认。
--
-- 到期提醒复用产品已有的到期提醒机制（域名/证书那套）。

ALTER TABLE mcp_tokens
  -- NULL = 永久有效。⚠️ 不能用零值日期表示永久 ——
  -- 那会让"永久"在任何按时间排序/比较的地方表现成"早就过期了"
  ADD COLUMN expires_at DATETIME NULL DEFAULT NULL COMMENT '到期时刻，NULL=永久有效';

-- ⚠️ 不给已有令牌补有效期。
--
-- 它们正在被人用着，迁移里悄悄给一个到期日，表现是某天 AI 突然全线 401，
-- 而没有任何地方提示发生过什么。设有效期必须是管理员看着界面做的决定
-- （同 109 那次"不给老 token 降权"的取舍）。
