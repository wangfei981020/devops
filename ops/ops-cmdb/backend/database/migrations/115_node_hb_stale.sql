-- 节点失联判定改为「采集时刻用真实心跳算好，存成一列」。
--
-- 原来的做法是：存一个心跳时间戳，展示时拿 NOW() 去减。
-- 但存进去的那个时间戳被 bucketHeartbeat 向下取整到 5 分钟了（为了压写放大），
-- 而判定阈值 heartbeatStaleAfter 也是 5 分钟 —— 取整本身就足以把健康节点推过线。
--
-- 实测后果（UAT 16 台节点）：8 台被标成「失联」，另 8 台正常，两组年龄正好差 5 分钟。
-- 分组依据只是真实心跳落在 5 分钟边界的哪一侧，与节点健康毫无关系。
-- 这 8 台的 ready_status=Ready、conditions 全绿、stuck=0，是彻头彻尾的假告警。
--
-- ⚠️ 单纯调大阈值治不了根：健康节点的展示年龄上界 = 取整粒度 + 采集间隔，
-- 两者都可能被调，阈值就得跟着改，迟早再次对不上。
-- 所以把判定挪到采集时刻——那里拿得到未取整的心跳，精度与存储策略彻底解耦。
ALTER TABLE k8s_nodes
  ADD COLUMN hb_stale TINYINT NOT NULL DEFAULT 0
  COMMENT '采集时刻判定：真实心跳是否已超过 heartbeatStaleAfter。不要用 last_heartbeat 倒推，那个值是取整过的';

-- 存量行没有这个判定结果。回填成 0（不失联）是安全的：
-- 下一轮采集（默认 120 秒）就会用真实心跳覆盖掉。
-- 回填成 1 反而会让全部节点先红一轮。
