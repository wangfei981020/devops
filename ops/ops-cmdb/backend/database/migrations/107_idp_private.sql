-- 允许把身份源指向内网 / http —— 必须由管理员显式勾选。
--
-- 背景：106 一律拒绝内网地址和 http，理由是 SSRF（这个接口由服务端发请求，
-- 允许指向内网就等于给了一个探测内网的入口）。这个理由本身没错，
-- 但它把一整类**完全正常**的客户挡在门外：
-- 自建 Keycloak、AD FS、内网 Authelia 基本都跑在私网地址上，
-- 很多还只有 http（TLS 在入口层终止）。他们不是攻击者，他们是典型客户。
--
-- 所以改成"默认拒绝 + 显式打开"，而不是二选一：
--   - 默认关：手滑填了 169.254.169.254（云元数据地址）不会真的发出去
--   - 打开：是一次有意识的决定，界面上会说清放开了什么，日志里也留痕
--
-- ⚠️ 关键在于**不能让它默认开着**。默认开的话，这个开关等于不存在。
ALTER TABLE idp_configs ADD COLUMN allow_private TINYINT NOT NULL DEFAULT 0
  COMMENT '允许 issuer 指向内网地址或使用 http（自建身份源场景）';
