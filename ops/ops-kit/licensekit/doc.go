// Package licensekit 是所有企业版产品共用的授权内核。
//
// # 为什么共用
//
// 客户买的是「产品套件」，不是一堆互不相干的系统。装三个产品要三个激活码、
// 三次填组织信息、三个到期日 —— 那是把内部的模块边界暴露给客户当负担。
// 一个 license 覆盖多产品，是客户视角唯一说得通的做法。
//
// # 职责边界
//
//	本包负责：Ed25519 验签 · 安装指纹 · 有效期与宽限期 · 状态机 · Payload 外壳
//	产品负责：自己的 Feature 枚举 · Capacity 字段名 · implemented 表 · 门控点
//
// 本包**不知道**任何产品有什么功能 —— Features 在这里就是字符串。
// 这样加一个新产品不需要动共享库。
//
// # 三条不能妥协的设计（改起来代价极高，写在最前面）
//
//  1. 按 feature 逐项判定，绝不写成「有效 license = 全给」。
//     写成全有全无就永远卖不了功能分档；等 license 发出去再改，
//     已发出的那些里没有 features 列表，改判定等于让老客户功能全失效。
//
//  2. 过期不停服：降级只读 + 顶部横幅，宽限 30 天。
//     运维类系统尤其如此 —— 故障期间把它降级，等于在故障上再加一层故障。
//
//  3. 容量超限只警告不阻断。客户临时扩容结果系统罢工，这是会丢客户的设计。
package licensekit
