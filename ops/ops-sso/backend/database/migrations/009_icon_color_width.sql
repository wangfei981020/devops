-- 放宽应用图标底色列。
--
-- # 为什么
--
-- 原来是 VARCHAR(16)，够放 `#5B4BD8`（7 字符）。
-- 后来界面改成按标识哈希自动生成底色，生成的是设计系统在用的
-- `oklch(0.62 0.14 200)` —— 20 字符，放不下。
--
-- 后果不是截断而是**整条插入失败**：
--   Error 1406: Data too long for column 'icon_color'
-- 也就是「用界面接入应用」这条路直接 500，而接入应用是装上这套系统的第一步。
--
-- ⚠️ 这个 bug 上线了一段时间没被发现，因为加完自动生成之后
-- 一直没有再通过表单建过应用 —— 只是看了看已有几行显示正常。
-- 「改完看一眼旧数据没坏」不等于「新写入这条路还通」。
--
-- 32 而不是刚好够：oklch 还可能带透明度（`oklch(0.62 0.14 200 / 0.8)`），
-- 卡着写会在下一次改色时再撞一遍。
ALTER TABLE apps MODIFY COLUMN icon_color VARCHAR(32) NOT NULL DEFAULT '';
